# Багованный код
students = ["Аня", "Гена", "Катя"]
grades = dict.fromkeys(students, [])   # хотим: у каждого студента свой пустой список оценок

grades["Аня"].append(5)
grades["Гена"].append(3)
grades["Катя"].append(4)

print(grades)
# Ожидали: {'Аня': [5], 'Гена': [3], 'Катя': [4]}
# Получили: {'Аня': [5, 3, 4], 'Гена': [5, 3, 4], 'Катя': [5, 3, 4]}


# dict.fromkeys(keys, value) создаёт один объект [] и кладёт ссылку на него
# под каждый ключ. Получается алиасинг: все три значения - это один и тот же
# список, поэтому append через любой ключ меняет «все» списки сразу.


# Исправленная версия
students = ["Аня", "Гена", "Катя"]
grades = {name: [] for name in students}   # [] вычисляется заново для каждого ключа

grades["Аня"].append(5)
grades["Гена"].append(3)
grades["Катя"].append(4)

print(grades)   # {'Аня': [5], 'Гена': [3], 'Катя': [4]}
